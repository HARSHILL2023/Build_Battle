import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { Issue } from "../src/models/Issue";
import { reserveSeq } from "../src/utils/seq";
import {
  createTestUser,
  loginAgent,
  startTestApp,
  stopTestApp,
  type AuthedClient,
  type TestContext,
} from "./helpers";

let ctx: TestContext;
let authed: AuthedClient;

beforeAll(async () => {
  ctx = await startTestApp();
  await createTestUser("issues-admin@example.com", "admin");
  authed = await loginAgent(ctx.app, "issues-admin@example.com");
  await authed.withCsrf(authed.agent.post("/api/import")).send({ sample: "official-500" });
  await authed.withCsrf(authed.agent.post("/api/analyze")).send({ method: "deterministic" });
});

afterAll(async () => {
  await stopTestApp(ctx);
});

describe("GET /api/issues", () => {
  it("lists issues sorted by priority", async () => {
    const res = await authed.agent.get("/api/issues");
    expect(res.status).toBe(200);
    expect(res.body.issues.length).toBeGreaterThan(0);
    const scores = res.body.issues.map((i: { priority_score: number }) => i.priority_score);
    expect([...scores].sort((a, b) => b - a)).toEqual(scores);
  });

  it("filters by valid status and ignores invalid ones", async () => {
    const open = await authed.agent.get("/api/issues?status=open");
    expect(open.status).toBe(200);
    for (const i of open.body.issues) expect(i.status).toBe("open");
    const all = await authed.agent.get("/api/issues?status=bogus");
    expect(all.status).toBe(200);
    expect(all.body.issues.length).toBeGreaterThanOrEqual(open.body.issues.length);
  });
});

describe("GET /api/issues/:id", () => {
  it("returns the issue with evidence rows", async () => {
    const list = await authed.agent.get("/api/issues");
    const id = list.body.issues[0].id as number;
    const res = await authed.agent.get(`/api/issues/${id}`);
    expect(res.status).toBe(200);
    expect(res.body.issue.id).toBe(id);
    expect(Array.isArray(res.body.evidence)).toBe(true);
    expect(res.body.evidence.length).toBeGreaterThan(0);
  });

  it("returns 400 for invalid ids and 404 for missing ones", async () => {
    expect((await authed.agent.get("/api/issues/nope")).status).toBe(400);
    expect((await authed.agent.get("/api/issues/999999")).status).toBe(404);
  });
});

describe("PATCH /api/issues/:id", () => {
  it("updates status with valid values", async () => {
    const list = await authed.agent.get("/api/issues");
    const id = list.body.issues[0].id as number;
    const res = await authed.withCsrf(authed.agent.patch(`/api/issues/${id}`)).send({ status: "in_progress" });
    expect(res.status).toBe(200);
    expect(res.body.issue.status).toBe("in_progress");
  });

  it("rejects invalid statuses with 400", async () => {
    const list = await authed.agent.get("/api/issues");
    const id = list.body.issues[0].id as number;
    const res = await authed.withCsrf(authed.agent.patch(`/api/issues/${id}`)).send({ status: "done" });
    expect(res.status).toBe(400);
  });

  it("returns 404 for missing issues", async () => {
    const res = await authed.withCsrf(authed.agent.patch("/api/issues/999999")).send({ status: "resolved" });
    expect(res.status).toBe(404);
  });
});

describe("DELETE /api/issues/:id", () => {
  it("refuses auto-generated issues with 404", async () => {
    const list = await authed.agent.get("/api/issues");
    const id = list.body.issues[0].id as number;
    const res = await authed.withCsrf(authed.agent.delete(`/api/issues/${id}`)).send();
    expect(res.status).toBe(404);
  });

  it("deletes manual issues", async () => {
    const sqliteId = await reserveSeq("issue", 1);
    await Issue.create({
      title: "Manual test issue",
      description: "d",
      category: "Other",
      primaryTopic: "product-quality",
      frequencyRaw: 1,
      frequencyUnique: 1,
      negativeCount: 0,
      priorityScore: 10,
      priorityBand: "low",
      priorityExplanation: "test",
      recommendation: "test",
      evidenceIds: [],
      status: "open",
      autoGenerated: false,
      sqliteId,
    });
    const res = await authed.withCsrf(authed.agent.delete(`/api/issues/${sqliteId}`)).send();
    expect(res.status).toBe(200);
    expect((await authed.agent.get(`/api/issues/${sqliteId}`)).status).toBe(404);
  });
});
