import mongoose, { Schema } from "mongoose";

const IssueSchema = new Schema(
  {
    title: { type: String, required: true },
    description: { type: String, required: true, default: "" },
    category: { type: String, required: true, default: "" },
    primaryTopic: { type: String, required: true, default: "" },
    frequencyRaw: { type: Number, required: true, default: 0 },
    frequencyUnique: { type: Number, required: true, default: 0 },
    negativeCount: { type: Number, required: true, default: 0 },
    priorityScore: { type: Number, required: true, default: 0 },
    priorityBand: { type: String, enum: ["high", "medium", "low"], required: true, default: "low" },
    priorityExplanation: { type: String, required: true, default: "" },
    recommendation: { type: String, required: true, default: "" },
    evidenceIds: { type: [Number], required: true, default: [] },
    status: { type: String, enum: ["open", "in_progress", "resolved"], default: "open" },
    autoGenerated: { type: Boolean, default: true },
    sqliteId: { type: Number, unique: true, sparse: true },
  },
  { timestamps: true }
);

IssueSchema.index({ priorityScore: -1 });

export const Issue = mongoose.models.Issue ?? mongoose.model("Issue", IssueSchema);
