import type { Request, Response } from "express";
import { Feedback } from "../models/Feedback.js";
import { Issue } from "../models/Issue.js";
import { asyncHandler } from "../utils/errors.js";
import { issueRow } from "../utils/serialize.js";

const VALID_STATUS = ["open", "in_progress", "resolved"];

function parseId(id: unknown): number | null {
  if (typeof id !== "string") return null;
  const n = Number(id);
  return Number.isInteger(n) && n > 0 ? n : null;
}

function toRow(doc: Record<string, unknown>): Record<string, unknown> {
  return issueRow({
    sqliteId: doc["sqliteId"] as number,
    title: doc["title"] as string,
    description: (doc["description"] as string) ?? "",
    category: (doc["category"] as string) ?? "",
    primaryTopic: (doc["primaryTopic"] as string) ?? "",
    frequencyRaw: doc["frequencyRaw"] as number,
    frequencyUnique: doc["frequencyUnique"] as number,
    negativeCount: doc["negativeCount"] as number,
    priorityScore: doc["priorityScore"] as number,
    priorityBand: doc["priorityBand"] as string,
    priorityExplanation: (doc["priorityExplanation"] as string) ?? "",
    recommendation: (doc["recommendation"] as string) ?? "",
    evidenceIds: (doc["evidenceIds"] as number[]) ?? [],
    status: doc["status"] as string,
    autoGenerated: Boolean(doc["autoGenerated"]),
    createdAt: doc["createdAt"] as Date | undefined,
    updatedAt: doc["updatedAt"] as Date | undefined,
  });
}

export const listIssues = asyncHandler(async (req: Request, res: Response) => {
  try {
    const status = typeof req.query.status === "string" ? req.query.status : "";
    const filter = VALID_STATUS.includes(status) ? { status } : {};
    const docs = (await Issue.find(filter).sort({ priorityScore: -1, sqliteId: 1 }).lean()) as Record<string, unknown>[];
    res.json({ issues: docs.map(toRow) });
  } catch (err) {
    console.error("GET /api/issues failed:", err instanceof Error ? err.message : String(err));
    res.status(500).json({ error: "Could not load issues." });
  }
});

export const getIssue = asyncHandler(async (req: Request, res: Response) => {
  try {
    const id = parseId(req.params.id);
    if (id === null) {
      res.status(400).json({ error: "Invalid issue id." });
      return;
    }
    const doc = (await Issue.findOne({ sqliteId: id }).lean()) as Record<string, unknown> | null;
    if (!doc) {
      res.status(404).json({ error: "Issue not found." });
      return;
    }
    const evidenceIds = (doc["evidenceIds"] as number[]) ?? [];
    let evidence: unknown[] = [];
    if (evidenceIds.length > 0) {
      const rows = (await Feedback.find({ sqliteId: { $in: evidenceIds } })
        .select("sqliteId reviewText sourceCategory sentiment")
        .lean()) as { sqliteId: number; reviewText: string; sourceCategory: string; sentiment: string | null }[];
      evidence = rows.map((r) => ({
        id: r.sqliteId,
        review_text: r.reviewText,
        source_category: r.sourceCategory,
        sentiment: r.sentiment,
      }));
    }
    res.json({ issue: toRow(doc), evidence });
  } catch (err) {
    console.error("GET /api/issues/[id] failed:", err instanceof Error ? err.message : String(err));
    res.status(500).json({ error: "Could not load issue." });
  }
});

export const deleteIssue = asyncHandler(async (req: Request, res: Response) => {
  try {
    const id = parseId(req.params.id);
    if (id === null) {
      res.status(400).json({ error: "Invalid issue id." });
      return;
    }
    const result = await Issue.deleteOne({ sqliteId: id, autoGenerated: false });
    if (result.deletedCount === 0) {
      res.status(404).json({ error: "Issue not found, or it is auto-generated and managed by analysis." });
      return;
    }
    res.json({ message: "Issue deleted." });
  } catch (err) {
    console.error("DELETE /api/issues/[id] failed:", err instanceof Error ? err.message : String(err));
    res.status(500).json({ error: "Could not delete issue." });
  }
});

export const patchIssue = asyncHandler(async (req: Request, res: Response) => {
  try {
    const id = parseId(req.params.id);
    if (id === null) {
      res.status(400).json({ error: "Invalid issue id." });
      return;
    }
    const body = (req.body ?? {}) as { status?: string };
    if (!body.status || !VALID_STATUS.includes(body.status)) {
      res.status(400).json({ error: "Status must be open, in_progress, or resolved." });
      return;
    }
    const updated = await Issue.findOneAndUpdate(
      { sqliteId: id },
      { $set: { status: body.status } },
      { returnDocument: "after" }
    ).lean();
    if (!updated) {
      res.status(404).json({ error: "Issue not found." });
      return;
    }
    res.json({ issue: toRow(updated as Record<string, unknown>) });
  } catch (err) {
    console.error("PATCH /api/issues failed:", err instanceof Error ? err.message : String(err));
    res.status(500).json({ error: "Could not update issue." });
  }
});
