import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  /* InsightFlow serves database-backed dynamic routes, so the static
     Cache Components model is disabled in favor of explicit
     `force-dynamic` route segments. */
  serverExternalPackages: ["better-sqlite3"],
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async headers() {
    // Next.js App Router hydrates through inline <script> payloads
    // (self.__next_f). A strict script-src 'self' blocks hydration, so
    // inline scripts must be allowed. This stays safe here because all
    // rendered content is React-escaped (no raw-HTML sinks) and only
    // same-origin scripts load; every other directive stays strict.
    const csp = [
      "default-src 'self'",
      "script-src 'self' 'unsafe-inline'",
      "style-src 'self' 'unsafe-inline'",
      "img-src 'self' data:",
      "font-src 'self' data:",
      "connect-src 'self'",
      "frame-ancestors 'self'",
      "base-uri 'self'",
      "form-action 'self'",
    ].join("; ");
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "SAMEORIGIN" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
          {
            key: "Strict-Transport-Security",
            value: "max-age=63072000; includeSubDomains",
          },
        ],
      },
    ];
  },
};

export default nextConfig;
